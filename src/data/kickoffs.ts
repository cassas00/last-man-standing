function pad(n: number): string {
  return String(n).padStart(2, "0");
}

export function kickoffIso(matchNumber: number): string | undefined {
  const k = kickoffsEt[matchNumber];
  if (!k) return undefined;
  const [month, day, hour, minute = 0] = k;
  return `2026-${pad(month)}-${pad(day)}T${pad(hour)}:${pad(minute)}:00${EDT}`;
}

